'''Arithematic operators (+, -, *, /, //, %, **)
   Floor division only provide us  the integer value of division
 Modulus operator provide us the remainder of the division
 Exponentiation operator (**)is used to power something 
'''
print("Addition", 2+3)
print("Subtraction", 7-2)
print("Multiplication", 5*4)
print("Division", 7/3)
print("Floor division", 7//3)
print("Modulus operatior", 7%3)
print("Exponentiation", 6**2)

'''Relational Operator (>,<,>=,<=, ==, !=)
 it gives output in bool
'''
print(5>10)
print(5<10)
print(5>=5)
print(10<=10)
print(5==5)
print(7==8)

print(5!=5)
print(5!=7)

#Logical Operator(and, or , not)
# When we use and operator we get true only when both are true
print(True and False)
print(False and False)
print(True and True)
print(False and True)
#When we use or operator we get false only when both are false
print(True or True)
print(True or False)
print(False or False)
print(False or False)

# not operator invert bool value
print(not (True))
print(not False)

